"""Finite groups as explicit multiplication tables (n <= ~2000), built from permutation generators.
Each group dict: n, mul (n x n int array, mul[g,h] = index of g*h), inv (array), ident=0, name,
rmul(g) -> array h -> h*g, sample(rng) -> random non-identity element, is_inv(g), mulf(g,h).
Elements are integer indices; index 0 is the identity.
"""
import numpy as np
import itertools


def from_perms(gens, name):
    deg = len(gens[0])
    ident = tuple(range(deg))
    elems = [ident]; idx = {ident: 0}
    frontier = [ident]
    gens = [tuple(g) for g in gens]
    while frontier:
        nf = []
        for p in frontier:
            for g in gens:
                q = tuple(g[p[i]] for i in range(deg))   # p then g  (composition: apply p, then g)
                if q not in idx:
                    idx[q] = len(elems); elems.append(q); nf.append(q)
        frontier = nf
        if len(elems) > 5000:
            raise ValueError('group too large')
    n = len(elems)
    E = np.array(elems, dtype=np.int64)
    # mul[a,b] = element "a then b": (a*b)[i] = b[a[i]]  (consistent with right action x -> x*g)
    mul = np.empty((n, n), dtype=np.int64)
    for a in range(n):
        for b in range(n):
            mul[a, b] = idx[tuple(E[b][E[a]])]
    return finalize(mul, name)


def finalize(mul, name):
    n = mul.shape[0]
    ident = int(np.where((mul == np.arange(n)[None, :]).all(axis=1))[0][0])
    # reindex so identity is 0
    if ident != 0:
        perm = np.arange(n); perm[0], perm[ident] = ident, 0
        inv_perm = np.argsort(perm)
        mul = inv_perm[mul[np.ix_(perm, perm)]]
    inv = np.array([int(np.where(mul[g] == 0)[0][0]) for g in range(n)], dtype=np.int64)
    H = dict(n=n, mul=mul, inverse=inv, ident=0, name=name)
    H['rmul'] = lambda g: mul[:, g]
    H['inv'] = lambda g: int(inv[g])
    H['mulf'] = lambda g, h: int(mul[g, h])
    H['is_inv'] = lambda g: g != 0 and int(mul[g, g]) == 0
    H['sample'] = lambda rng: int(rng.integers(1, n))
    H['params'] = (name,)
    return H


def direct_product(A, B):
    nA, nB = A['n'], B['n']
    mul = (A['mul'][:, None, :, None] * nB + B['mul'][None, :, None, :]).reshape(nA * nB, nA * nB)
    return finalize(mul, f"{A['name']}x{B['name']}")


def cyclic(k):
    mul = (np.arange(k)[:, None] + np.arange(k)[None, :]) % k
    return finalize(mul, f'C{k}')


def metacyclic(m, k, r):
    assert pow(r, k, m) == 1 % m
    rp = np.array([pow(r, j, m) for j in range(k)])
    n = m * k
    I = np.arange(n) // k; J = np.arange(n) % k
    mul = ((I[:, None] + rp[J][:, None] * I[None, :]) % m) * k + (J[:, None] + J[None, :]) % k
    return finalize(mul, f'Z{m}x|_{r}Z{k}')


def psl2(p):
    """PSL(2,p) acting on the projective line {0..p-1, inf=p}."""
    def mob(a, b, c, d):
        perm = []
        for x in range(p + 1):
            if x == p:
                y = p if c == 0 else (a * pow(c, p - 2, p)) % p
            else:
                num = (a * x + b) % p; den = (c * x + d) % p
                y = p if den == 0 else (num * pow(den, p - 2, p)) % p
            perm.append(y)
        return perm
    return from_perms([mob(1, 1, 0, 1), mob(0, p - 1, 1, 0)], f'PSL2_{p}')


def pgl2(p):
    def mob(a, b, c, d):
        perm = []
        for x in range(p + 1):
            if x == p:
                y = p if c == 0 else (a * pow(c, p - 2, p)) % p
            else:
                num = (a * x + b) % p; den = (c * x + d) % p
                y = p if den == 0 else (num * pow(den, p - 2, p)) % p
            perm.append(y)
        return perm
    # generator of F_p^*
    g = next(x for x in range(2, p) if all(pow(x, (p - 1) // f, p) != 1 for f in range(2, p) if (p - 1) % f == 0 and all(f % d for d in range(2, f))))
    return from_perms([mob(1, 1, 0, 1), mob(0, p - 1, 1, 0), mob(g, 0, 0, 1)], f'PGL2_{p}')


def alternating(nn):
    if nn % 2 == 1:
        c = list(range(1, nn)) + [0]                 # n-cycle (even permutation for odd n)
    else:
        c = [0] + list(range(2, nn)) + [1]           # (n-1)-cycle on {1..n-1}
    t = list(range(nn)); t[0], t[1], t[2] = 1, 2, 0  # (0 1 2)
    return from_perms([c, t], f'A{nn}')


def symmetric(nn):
    c = list(range(1, nn)) + [0]
    t = list(range(nn)); t[0], t[1] = 1, 0
    return from_perms([c, t], f'S{nn}')


def matrix_group(gens_mats, p, name):
    """Group generated by invertible matrices over F_p acting on nonzero vectors (faithful)."""
    s = len(gens_mats[0])
    vecs = [v for v in itertools.product(range(p), repeat=s) if any(v)]
    vidx = {v: i for i, v in enumerate(vecs)}
    perms = []
    for M in gens_mats:
        M = np.array(M) % p
        perms.append([vidx[tuple((M @ np.array(v)) % p)] for v in vecs])
    return from_perms(perms, name)


def sl2(p):
    return matrix_group([[[1, 1], [0, 1]], [[0, p - 1], [1, 0]]], p, f'SL2_{p}')


def gl2(p):
    g = 2 if p != 2 else 1
    return matrix_group([[[1, 1], [0, 1]], [[0, p - 1], [1, 0]], [[g, 0], [0, 1]]], p, f'GL2_{p}')
